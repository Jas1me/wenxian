def init_db(force=False):
    if force and os.path.exists(DB_PATH):
        os.remove(DB_PATH)
    conn = sqlite3.connect(DB_PATH)
    conn.executescript(SCHEMA)
    cur = conn.cursor()
    cur.execute("SELECT COUNT(*) FROM articles")
    if cur.fetchone()[0] == 0:
        for a in SEED_ARTICLES:
            cur.execute(
                """INSERT OR IGNORE INTO articles
                   (pmid,title,authors,journal,year,pub_type,abstract,keywords,doi,url,impact_factor,collection)
                   VALUES (?,?,?,?,?,?,?,?,?,?,?,?)""",
                (a["pmid"], a["title"], a["authors"], a["journal"], a["year"], a["pub_type"],
                 a["abstract"], a["keywords"], a["doi"], a["url"], None, a["collection"]))
        conn.commit()
    conn.close()
    return DB_PATH

